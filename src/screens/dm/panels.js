const issueLine = error => `${safeLabel(error.code)} · ${safeLabel(error.path)}: ${safeLabel(error.message)}`;

/** Story Block's verdict on the pack with the open draft in place. Returns the lines shown. */
export function verdictLines(S) {
    const verdict = checkModules(S.studio.model, S.candidate());
    const lines = [];
    if (verdict.waiting) lines.push(`Not checked: ${WAITING_MESSAGE}.`);
    else if (verdict.ok) lines.push('Accepted by Story Block.');
    for (const error of verdict.errors.slice(0, 20)) lines.push(issueLine(error));
    for (const found of verdict.v11) lines.push(`${found.code} · ${found.path}: ${found.message}`);
    if (verdict.errors.length > 20) lines.push(`and ${verdict.errors.length - 20} more`);
    return { lines, verdict };
}

export function grammarPanel(S, host) {
    const { doc } = S;
    host.replaceChildren();
    host.append(heading(doc, 'Narrator grammar', 'h2'));
    const preview = grammarPreview(S.candidateDocument(), S.draft);
    host.append(note(doc, preview.storyBlockText ? 'Generated by Story Block.' : 'Studio preview of the grammar Story Block generates from these declarations.'));
    host.append(el(doc, 'p', `Reference: ${preview.ref}${preview.short ? ' (short form: unique in this pack)' : ' (full ID: the slug is not unique in this pack)'}`, { id: 'dm-grammar-ref' }));
    if (preview.storyBlockText) host.append(el(doc, 'pre', preview.storyBlockText, { id: 'dm-grammar-sb' }));
    if (!preview.kinds.length) host.append(note(doc, 'No kinds yet. Add a kind to see its line.'));
    for (const kind of preview.kinds) {
        const box = card(doc);
        box.setAttribute('data-grammar-kind', kind.name);
        box.append(heading(doc, kind.name, 'h3'), el(doc, 'pre', kind.line, { class: 'grammar-line' }), note(doc, kind.onceText));
        for (const label of kind.labels) box.append(el(doc, 'p', `${label.name} (${label.type}): ${label.domain}`, { class: 'muted' }));
        for (const item of kind.conditions) box.append(el(doc, 'p', `Applies only when ${item.when}.${item.message ? ` Otherwise refused: ${item.message}` : ''}`, { class: 'muted' }));
        if (kind.v11) box.append(note(doc, 'check: needs data-modules v1.1', 'warning'));
        if (kind.effects.length) box.append(el(doc, 'p', `Effects: ${kind.effects.join('; ')}`, { class: 'muted' }));
        box.append(el(doc, 'strong', 'Valid example'));
        for (const line of kind.examples.valid) {
            const sample = el(doc, 'pre', line, { class: 'example-valid' });
            box.append(sample, button(doc, 'Use in simulator', () => S.useInSimulator(line), { 'aria-label': `Use ${kind.name} example in simulator` }));
        }
        if (kind.examples.refused.length) box.append(el(doc, 'strong', 'Lines expected to be refused'));
        for (const item of kind.examples.refused) box.append(el(doc, 'pre', item.line, { class: 'example-refused' }), el(doc, 'p', `${item.code}: ${item.why}`, { class: 'muted' }));
        host.append(box);
    }
    for (const template of preview.templates) {
        const box = card(doc, heading(doc, `Reward template ${template.name}`, 'h3'));
        for (const value of template.values) {
            if (value.table) for (const branch of value.table) box.append(el(doc, 'p', `${value.name} when ${value.binding} is ${branch.key}: ${branch.min} to ${branch.max}, picker ${branch.pick}${branch.picked === null ? '' : ` \u2192 ${branch.picked}`}`, { class: 'muted' }));
            else box.append(el(doc, 'p', `${value.name}: ${value.min} to ${value.max}, picker ${value.pick}${value.picked === null ? '' : ` \u2192 ${value.picked}`}`, { class: 'muted' }));
        }
        for (const binding of template.bindings) box.append(el(doc, 'p', `Narrator chooses ${binding.name}: ${binding.domain}`, { class: 'muted' }));
        host.append(box);
    }
    if (preview.kinds.length) host.append(button(doc, 'Copy grammar text', () => { S.studio.win?.navigator?.clipboard?.writeText?.(grammarText(preview)); }));
}

export function referencesSection(S, host) {
    const { doc, studio } = S;
    const model = studio.model;
    const saved = modulesOf(model.document);
    const dirty = S.dirty();
    host.append(note(doc, 'Rename or remove a module, export, template, field, key, import, label, binding or value. Every reference is rewritten by position in the pack, never by matching text. These edits apply to the saved pack, as one Undo step.'));
    if (dirty) { host.append(note(doc, 'Apply or discard the draft first: references are rewritten in the saved pack.', 'warning')); return; }
    const all = targets(model.document);
    if (!all.length) { host.append(note(doc, 'No data module records yet.')); return; }
    const state = S.state;
    const options = all.map(item => [`${item.targetKind}\u0000${item.targetId}`, `${item.targetKind.slice(3)} · ${item.targetId} · ${item.count} reference${item.count === 1 ? '' : 's'}`]);
    if (!options.some(([key]) => key === state.refTarget)) state.refTarget = options[0][0];
    selectControl(doc, host, 'Reference target', options, state.refTarget, value => { state.refTarget = value; S.redraw(); }, { id: 'dm-ref-target' });
    const [targetKind, targetId] = state.refTarget.split('\u0000');
    const target = { targetKind, targetId };
    const refs = inboundReferences(model.document, target, indexDataModuleReferences(model.document));
    const list = el(doc, 'ul', '', { id: 'dm-ref-list' });
    for (const ref of refs) list.append(el(doc, 'li', `${pathText(ref.path)} (${ref.via})`));
    host.append(heading(doc, `${refs.length} reference${refs.length === 1 ? '' : 's'}`, 'h3'), refs.length ? list : note(doc, 'Nothing else refers to it.'));
    const input = textControl(doc, host, 'New name', '', () => {}, { id: 'dm-ref-name' });
    host.append(row(doc,
        button(doc, 'Rename everywhere', () => {
            if (applyEdit(studio, renameDataModuleTarget(studio.model, target, input.value))) S.afterRename?.(target, input.value);
        }, { 'aria-label': 'Rename target and its references' }),
        button(doc, 'Remove', () => {
            const result = removeDataModuleTarget(studio.model, target);
            if (!result.ok && result.references?.length) S.state.refRefused = result.references.map(ref => pathText(ref.path));
            applyEdit(studio, result);
        }, { 'aria-label': 'Remove target' })));
    if (state.refRefused?.length) {
        const refused = el(doc, 'ul', '', { id: 'dm-ref-refused' });
        for (const path of state.refRefused) refused.append(el(doc, 'li', path));
        host.append(note(doc, 'Removal refused. Still referenced at:', 'warning'), refused);
    }
}

export function jsonSection(S, host) {
    const { doc, draft } = S;
    host.append(note(doc, 'The whole record, including keys the forms do not show. Edit it here to repair anything the forms cannot represent, then press Use record JSON. Unknown keys stay in the record until you remove them.'));
    const area = el(doc, 'textarea', '', { id: 'dm-json', 'aria-label': 'Record JSON', rows: '18', spellcheck: 'false' });
    area.value = JSON.stringify(draft, null, 2);
    const error = el(doc, 'p', '', { class: 'warning', role: 'status', id: 'dm-json-error' });
    area.addEventListener('input', () => {
        const parsed = parseJsonInput(area.value);
        const bad = !parsed.ok || !isObject(parsed.value);
        area.setAttribute('data-json-invalid', bad ? 'true' : 'false');
        error.textContent = bad ? `JSON refused: ${parsed.ok ? 'a data module is a JSON object' : parsed.error}` : '';
    });
    host.append(area, error);
    host.append(button(doc, 'Use record JSON', () => {
        const parsed = parseJsonInput(area.value);
        if (!parsed.ok || !isObject(parsed.value)) { error.textContent = `JSON refused: ${parsed.ok ? 'a data module is a JSON object' : parsed.error}`; return; }
        replaceContents(draft, parsed.value);
        S.redraw();
    }), button(doc, 'Reload from form', () => { area.value = JSON.stringify(draft, null, 2); area.setAttribute('data-json-invalid', 'false'); error.textContent = ''; }));
    const unknown = unknownPaths(draft);
    const unknownList = el(doc, 'ul', '', { id: 'dm-unknown' });
    for (const path of unknown) unknownList.append(el(doc, 'li', path));
    host.append(heading(doc, 'Not shown in the forms', 'h3'), unknown.length ? unknownList : note(doc, 'Every key in this record has a form control.'));
    S.listeners.push(() => { if (doc.activeElement !== area && area.getAttribute('data-json-invalid') !== 'true') area.value = JSON.stringify(draft, null, 2); });
}

