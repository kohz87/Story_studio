// Deterministic offline distribution: no runtime loader or external assets.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { ASSETS, SB_ICONS } from '../src/assets/index.js';
import { ICON_SET } from '../vendor/story-block/src/v2/view/icons/set.js';

const drawings = {};
for (const [name, source] of Object.entries(ASSETS)) {
    const stack = [];
    let root;
    for (const match of source.matchAll(/<(\/?)([\w-]+)([^>]*?)(\/?)>/g)) {
        if (match[1]) { stack.pop(); continue; }
        const attrs = Object.fromEntries([...match[3].matchAll(/([\w:-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
        delete attrs.xmlns;
        const node = [match[2], attrs, []];
        if (stack.length) stack.at(-1)[2].push(node); else root = node;
        if (!match[4]) stack.push(node);
    }
    drawings[name] = root;
}
for (const [name, id] of Object.entries(SB_ICONS)) {
    drawings[name] = ['svg', { viewBox: '0 0 256 256', fill: 'currentColor', 'aria-hidden': 'true' }, [
        ['path', { d: ICON_SET[id].regular }, []],
    ]];
}
await writeFile('src/assets/drawings.js', `// Generated by scripts/build.mjs from the licensed source assets.\nexport const DRAWINGS = ${JSON.stringify(drawings)};\n`);
const result = await build({ entryPoints: ['src/studio.js'], bundle: true, format: 'iife', target: 'es2022', write: false, minify: true, legalComments: 'none' });
const css = await readFile('src/studio.css', 'utf8');
const credits = await readFile('src/credits.txt', 'utf8');
const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script').replaceAll('https://', 'https:\\u002f\\u002f');
const html = `<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; connect-src 'none'; base-uri 'none'; form-action 'none'"><title>Story Studio</title><style>\n${css}</style></head><body><div id="studio"></div><details class="credits"><summary>Credits and licences</summary><pre>${escape(credits)}</pre></details><script>\n${script}</script></body></html>\n`;
if (/fetch\s*\(|XMLHttpRequest|WebSocket|https?:\/\//.test(html.replaceAll('http://www.w3.org/2000/svg', ''))) throw new Error('Distribution contains a network reference');
await mkdir('dist', { recursive: true });
await writeFile('dist/story-studio.html', html);
console.log(`dist/story-studio.html: ${Buffer.byteLength(html)} bytes`);
