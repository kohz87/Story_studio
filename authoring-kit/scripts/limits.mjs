// Prints reference/LIMITS.md: Story Block's own limits and constants for packs, as a Markdown page.
//
//   node authoring-kit/scripts/limits.mjs                                    print it
//   node authoring-kit/scripts/limits.mjs > authoring-kit/reference/LIMITS.md   refresh the committed page
//
// Every number is read from what Story Block exports (the pack limits, the rules constants and schema, the data module
// limits), so the page cannot drift from the checker; a test fails when the committed page is not what this prints.
import { SB_V2 } from './sb-root.mjs';

const load = async name => import(new URL(name, SB_V2));
const { LIMITS, RECORD_LIMITS, ECONOMY_LIMITS, RANKS_LIMITS, RECIPE_LIMITS } = await load('packs/limits.js');
const { RULES_V2_CONSTANTS, RULES_V2_LIMITS, RULES_V2_PROGRESSION, RULES_V2_STATS, RULES_V2_SLOTS, rulesV2Schema } = await load('packs/rules-v2.js');
const { DM_LIMITS } = await load('data-modules/schema.js');

const defs = rulesV2Schema.$defs;
const props = rulesV2Schema.properties;
const group = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const range = node => node.const !== undefined ? `exactly ${node.const}`
    : node.minimum !== undefined || node.maximum !== undefined ? `${group(node.minimum ?? '')}${node.minimum !== undefined && node.maximum !== undefined ? ' to ' : ''}${node.maximum !== undefined ? group(node.maximum) : ''}`
        : node.minItems !== undefined || node.maxItems !== undefined ? `${node.minItems ?? 0} to ${node.maxItems} entries`
            : node.maxLength !== undefined ? `1 to ${node.maxLength} characters` : '';
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(row => `| ${row.join(' | ')} |`)].join('\n');
const e = defs.effect.oneOf;
const q = defs.closedQuest.properties;
const foe = defs.foe.properties;
const recipe = defs.recipe.properties;
const shop = defs.shop.properties;
const trainer = defs.trainer.properties;
const itemRule = defs.itemRule.properties;
const unit = defs.unit.properties;
const cost = defs.cost.properties;
const budgets = RULES_V2_CONSTANTS.classBudget;
const step = RULES_V2_CONSTANTS.pathBudgetIncrement;

const out = [];
const say = (...blocks) => out.push(blocks.join('\n\n'));

say('# Limits and constants', '',
    '*Generated by `node authoring-kit/scripts/limits.mjs` from the limits Story Block exports; do not edit by hand. The checker (`node authoring-kit/check.mjs`) is the final word.*');

say('## A pack file', table(['What', 'Limit'], [
    ['One pack file', `${group(LIMITS.packBytes)} bytes of UTF-8`],
    ['Nesting of objects and arrays', LIMITS.depth],
    ['Keys in one object', LIMITS.keys],
    ['Entries in one list (records of one kind included)', group(LIMITS.array)],
    ['Characters in one string', group(LIMITS.string)],
    ['A display name', `${LIMITS.name} characters`],
    ['A slug', `${RECORD_LIMITS.slug} characters: lowercase letters, digits and single dashes`],
    ['An item, place or skill-template note (host records)', `${RECORD_LIMITS.note} characters`],
    ['A tag or slot word', `${RECORD_LIMITS.word} characters`],
    ['Problems listed for one pack', `${LIMITS.errors}, then the checker stops: fix and run again`],
    ['Quest ranks in `content.ranks`', RANKS_LIMITS.records],
    ['Money scale (`economy.scale`)', `${ECONOMY_LIMITS.min} to ${ECONOMY_LIMITS.max}`],
    ['A recipe\'s difficulty `dc`', `${RECIPE_LIMITS.dcMin} to ${RECIPE_LIMITS.dcMax}`],
]));

say('## A rules pack (schema 2): sizes', table(['What', 'Limit'], [
    ['Classes', range(props.classes)],
    ['Skills', range(props.skills)],
    ['Written branches', range(props.branches)],
    ['Item rules (one per item in `content.items`)', range(props.itemRules)],
    ['Trainers', range(props.trainers)],
    ['A class\'s skills', `exactly ${defs.class.properties.skills.minItems}, each owned by one class`],
    ['A skill slug', `${RULES_V2_LIMITS.skillSlug} characters (room for the branch suffixes)`],
    ['A name', range(defs.name)],
    ['A note in the rules, foes and quests', `0 to ${defs.note.maxLength} characters`],
    ['All forms after expansion (bases, written and generated)', group(RULES_V2_LIMITS.forms)],
    ['The expanded rules as JSON', `${group(RULES_V2_LIMITS.resolvedBytes)} bytes`],
    ['Stats', RULES_V2_STATS.join(', ')],
    ['A stat value (foes, `requires`)', range(defs.stats.properties.STR)],
    ['Equipment slots', RULES_V2_SLOTS.join(', ')],
]));

say('## Classes, tiers and branches', table(['Tier', 'Unlocked at level', 'Base form budget', 'Step 1 form budget', 'Step 2 form budget'],
    RULES_V2_PROGRESSION.tiers.map(tier => [tier, tier === 0 ? 'the start' : `level ${RULES_V2_PROGRESSION.tierLevels[tier]}`, budgets[tier],
        tier === 3 ? budgets[tier] + step : 'no branches', tier === 3 ? budgets[tier] + 2 * step : 'no branches'])),
    `Tier 0 classes have parent \`null\`; every other class has a parent exactly one tier lower; every chain ends at tier 3. ` +
    `Only tier 3 skills have branches: ${RULES_V2_PROGRESSION.graph.perSkill.written} written per skill (${RULES_V2_PROGRESSION.graph.perClass.written} per tier 3 class) ` +
    `and ${RULES_V2_PROGRESSION.graph.perSkill.generated} generated (\`-g\`) by the engine (${RULES_V2_PROGRESSION.graph.perClass.generated} per class). ` +
    `A written branch must change behavior (target, element, effect kind, type, stat), not only numbers. ` +
    `The class cap leaves at most ${props.classes.maxItems - 3} tier 3 classes, since a tier 3 class needs its three ancestors.`);

say('## Skill base form', table(['Field', 'Allowed'], [
    ['`type`', defs.base.properties.type.enum.join(', ')],
    ['`cost.mp`, `cost.sp`', `${range(cost.mp)} (a physical skill has mp 0; every other type has sp 0)`],
    ['`cost.cooldown`', range(cost.cooldown)],
    ['`effects`', `${defs.base.properties.effects.minItems} to ${defs.base.properties.effects.maxItems}`],
    ['`unit` (summon or pet)', `null, or kind ${unit.kind.enum.join(' or ')}, statShare ${range(unit.statShare)}, poolShare ${range(unit.poolShare)}, rounds ${range(unit.rounds)}`],
    ['`element`', defs.element.enum.join(', ')],
    ['`target`', defs.target.enum.join(', ')],
]));

say('## Effects', table(['Effect', 'Fields and ranges'], [
    ['`damage`', `target one or all; power ${range(e[0].properties.power)}; element; damageType physical or magic`],
    ['`heal`, `shield`', `target self, ally or allies; power ${range(e[0].properties.power)}; element; damageType null`],
    ['`condition`', `kind ${e[1].properties.kind.enum.join(', ')}; chance ${range(e[1].properties.chance)}; rounds ${range(e[1].properties.rounds)}; harmful kinds (all but regen and guard) target one or all, regen and guard target self, ally or allies`],
    ['`stat`', `stat; amount ${range(e[2].properties.amount)} but not 0; rounds ${range(e[2].properties.rounds)}; a positive amount targets friends (self, ally, allies), a negative one foes (one, all)`],
]));

say('## Power budget', 'The checker adds a form\'s effects and compares the total with the form\'s budget:',
    table(['Effect', 'Score'], [
        ['damage, heal, shield', '`ceil(power / 10)`'],
        ['condition', '`ceil(chance / 25) * rounds`'],
        ['stat', '`2 * abs(amount) * rounds`'],
        ['target `all` or `allies`', 'the effect\'s score times 3'],
        ['`unit` is not null', 'plus 12 once'],
    ]),
    `Budgets: tier 0 ${budgets[0]}, tier 1 ${budgets[1]}, tier 2 ${budgets[2]}, tier 3 ${budgets[3]}; each branch step adds ${step} ` +
    `(a tier 3 step 1 form ${budgets[3] + step}, a step 2 form ${budgets[3] + 2 * step}). ` +
    'Example: a tier 0 single-target physical strike with power 100 scores 10 (fits 12); the same against `all` scores 30, which needs tier 2.',
    'Each form that has a generated child must survive the engine\'s power-up: +20 power on its first damage, heal or shield effect (so that power is at most 980), else +1 on its first stat amount (at most 9 in size), else +1 round on its first condition (at most 5). The power-up must fit the child\'s budget too.');

say('## Item rules', table(['Field', 'Allowed'], [
    ['`allowedSlots`', `${itemRule.allowedSlots.minItems} to ${itemRule.allowedSlots.maxItems} of the slots above; empty unless the item\'s kind is \`equipment\``],
    ['`hands`', `${itemRule.hands.enum.join(', ')}: weapons and off-hand items 1 (a two-hander 2, slot \`weapon\` only), everything else 0`],
    ['`requires`', 'minimum stats, each ' + range(defs.requires.properties.STR) + ', or `{}`'],
    ['`weight`', range(itemRule.weight)],
    ['`unique`', 'optional true or false'],
]));

say('## Foes, quests, shops, recipes, trainers', table(['Record', 'Limits'], [
    ['Foe', `tier ${range(foe.tier)}; level ${range(foe.level)}; all seven stats; skills ${foe.skills.minItems} to ${foe.skills.maxItems}; loot up to ${foe.loot.maxItems} lines (chance ${range(foe.loot.items.properties.chance)}, qty ${range(foe.loot.items.properties.qty)}); up to ${foe.loreTags.maxItems} loreTags`],
    ['Quest', `category ${q.category.enum.join(', ')}; up to ${q.requirements.maxItems} requirements; objectives ${q.objectives.minItems} to ${q.objectives.maxItems} (kill, collect, visit, story; counts ${range(defs.objective.oneOf[0].properties.count)}); reward items up to ${defs.reward.properties.items.maxItems}; \`durationMinutes\` null or ${range(q.durationMinutes.oneOf[1])}; \`repeat\` null or a cooldown of ${range(q.repeat.oneOf[1].properties.cooldownMinutes)} minutes`],
    ['Open quest template', `\`open: true\` and a \`rank\` that names a pack rank with a reward range; \`reward\` is coinMin, coinMax, xpMin, xpMax (coin and xp alike inside that rank\'s reward range, each min not above its max) and no items; \`repeat\` and \`chain\` are null`],
    ['Shop', `stock ${shop.stock.minItems} to ${shop.stock.maxItems} lines (qty ${range(shop.stock.items.properties.qty)}); \`kind\` a slug of at most 40 characters`],
    ['Recipe', `qty ${range(recipe.qty)}; materials ${recipe.materials.minItems} to ${recipe.materials.maxItems} (qty ${range(recipe.materials.items.properties.qty)}); minutes ${range(recipe.minutes)}; dc ${range(recipe.dc)}`],
    ['Trainer', `skills ${trainer.skills.minItems} to ${trainer.skills.maxItems}; fee ${range(trainer.fee)} (never 0); minutes exactly ${trainer.minutes.const}; up to ${trainer.eventTemplates.maxItems} eventTemplates`],
]));

say('## Progression the engine applies', table(['Constant', 'Value'], [
    ['Level cap', RULES_V2_CONSTANTS.levelCap],
    ['Start level, start stat, start points', `${RULES_V2_CONSTANTS.startLevel}, ${RULES_V2_CONSTANTS.startStat}, ${RULES_V2_CONSTANTS.startPoints}`],
    ['Points per level', RULES_V2_CONSTANTS.pointsPerLevel],
    ['Stat cap', RULES_V2_CONSTANTS.statCap],
    ['XP per level', RULES_V2_CONSTANTS.xpPerLevel],
    ['Class promotions at levels', RULES_V2_CONSTANTS.promotionMilestones.join(', ')],
    ['Skill path steps at levels', RULES_V2_CONSTANTS.pathMilestones.join(', ')],
    ['Mastery ranks reached at uses', RULES_V2_CONSTANTS.masteryAt.join(', ')],
    ['Training', `${RULES_V2_CONSTANTS.trainMinutes} minutes, ${RULES_V2_CONSTANTS.trainCredits} credits`],
]));

say('## Data modules (interpreter 1)', table(['What', 'Limit'], [
    ['Definitions in one pack', DM_LIMITS.definitions],
    ['Pins per chat, subjects per module', `${DM_LIMITS.pins}, ${DM_LIMITS.subjects}`],
    ['One definition', `${group(DM_LIMITS.definitionBytes)} bytes of JSON`],
    ['One instance (all its fields and timers)', `${group(DM_LIMITS.instanceBytes)} bytes`],
    ['Fields, kinds, rules, timers, reward templates', `${DM_LIMITS.fields}, ${DM_LIMITS.kinds}, ${DM_LIMITS.rules}, ${DM_LIMITS.timers}, ${DM_LIMITS.templates}`],
    ['Expression depth, nodes, effects in a list', `${DM_LIMITS.expressionDepth}, ${DM_LIMITS.expressionNodes}, ${DM_LIMITS.effects}`],
    ['Imports, offers', `${DM_LIMITS.imports}, ${DM_LIMITS.offers}`],
    ['Field, kind and label names', `lowercase, at most ${DM_LIMITS.slug} characters`],
    ['Enum values, map keys, text length', `${DM_LIMITS.enumValues}, ${DM_LIMITS.mapKeys}, ${DM_LIMITS.text}`],
    ['Migration steps', DM_LIMITS.migrations],
    ['Timer interval (`every`)', `1 to ${group(DM_LIMITS.elapsedMinutes)} minutes`],
    ['Whole numbers in expressions', `within plus or minus ${group(DM_LIMITS.integer)}`],
    ['Actions per reply: data roots, evaluation visits', `${DM_LIMITS.replyRoots}, ${group(DM_LIMITS.replyVisits)}`],
    ['Text the narrator is shown per module', `${group(DM_LIMITS.staticCharacters)} characters plus ${DM_LIMITS.tailTokens} tokens of state`],
    ['Problems listed', DM_LIMITS.errors],
]));

process.stdout.write(out.join('\n\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
