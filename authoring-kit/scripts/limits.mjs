// Prints the host's limits for packs and data modules.
import { SB_V2 } from './sb-root.mjs';

const { LIMITS, RECORD_LIMITS, CAST_LIMITS, PORTRAIT_LIMITS, ZIP_LIMITS } = await import(new URL('packs/limits.js', SB_V2));
const { DM_LIMITS } = await import(new URL('data-modules/schema.js', SB_V2));
const group = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(row => `| ${row.join(' | ')} |`)].join('\n');
const out = [];
const say = (...blocks) => out.push(blocks.join('\n\n'));
say('# Limits and constants', '*Generated by `node authoring-kit/scripts/limits.mjs` from Story Block limits.*');
say('## A pack file', table(['What', 'Limit'], [
    ['One pack', `${group(LIMITS.packBytes)} bytes of UTF-8`],
    ['Nesting', LIMITS.depth], ['Object keys', LIMITS.keys], ['List entries', LIMITS.array],
    ['String length', LIMITS.string], ['Display name', LIMITS.name], ['Slug length', RECORD_LIMITS.slug],
    ['Reported problems', LIMITS.errors],
]));

say('## The cast and its portraits', table(['What', 'Limit'], [
    ['People in one pack', CAST_LIMITS.entries],
    ['About, look, voice, personality, history', `${CAST_LIMITS.about}, ${CAST_LIMITS.look}, ${CAST_LIMITS.voice}, ${CAST_LIMITS.personality}, ${CAST_LIMITS.history} characters`],
    ['Name, place, goal and routine, drawn-to phrase', `${CAST_LIMITS.name}, ${CAST_LIMITS.place}, ${CAST_LIMITS.goal}, ${CAST_LIMITS.phrase} characters`],
    ['Aliases, drawn-to phrases, fields, secrets per person', `${CAST_LIMITS.aliases}, ${CAST_LIMITS.drawnTo}, ${CAST_LIMITS.fields}, ${CAST_LIMITS.secrets}`],
    ['Secret title, text, event', `${CAST_LIMITS.secretTitle}, ${CAST_LIMITS.secretText}, ${CAST_LIMITS.secretWhen} characters`],
    ['Secret rule', 'a meter and value, a story event, or both (opens at whichever comes first); at least one'],
    ['One portrait', `WebP, PNG or JPEG, ${PORTRAIT_LIMITS.bytes / 1024} KB at most`],
    ['Portrait files in one pack', PORTRAIT_LIMITS.perPack],
    ['A pack zip: the zip, unpacked in all, entries', `${ZIP_LIMITS.archive / 1048576} MB, ${ZIP_LIMITS.unpacked / 1048576} MB, ${ZIP_LIMITS.entries}`],
]));

say('## Data modules (interpreter 1)', table(['What', 'Limit'], [
    ['Definitions in one pack', DM_LIMITS.definitions],
    ['Pins per chat, subjects per module', `${DM_LIMITS.pins}, ${DM_LIMITS.subjects}`],
    ['One definition', `${group(DM_LIMITS.definitionBytes)} bytes of JSON`],
    ['One instance (all its fields and timers)', `${group(DM_LIMITS.instanceBytes)} bytes`],
    ['Fields, kinds, rules, timers, reward templates', `${DM_LIMITS.fields}, ${DM_LIMITS.kinds}, ${DM_LIMITS.rules}, ${DM_LIMITS.timers}, ${DM_LIMITS.templates}`],
    ['Expression depth, nodes, effects in a list', `${DM_LIMITS.expressionDepth}, ${DM_LIMITS.expressionNodes}, ${DM_LIMITS.effects}`],
    ['Imports, offers', `${DM_LIMITS.imports}, ${DM_LIMITS.offers}`],
    ['Field, kind and label names', `lowercase, at most ${DM_LIMITS.slug} characters`],
    ['Enum values, map keys, text length', `${DM_LIMITS.enumValues}, ${DM_LIMITS.mapKeys}, ${DM_LIMITS.text}`],
    ['Migration steps', DM_LIMITS.migrations],
    ['Timer interval (`every`)', `1 to ${group(DM_LIMITS.elapsedMinutes)} minutes`],
    ['Whole numbers in expressions', `within plus or minus ${group(DM_LIMITS.integer)}`],
    ['Actions per reply: data roots, evaluation visits', `${DM_LIMITS.replyRoots}, ${group(DM_LIMITS.replyVisits)}`],
    ['Text the narrator is shown per module', `${group(DM_LIMITS.staticCharacters)} characters plus ${DM_LIMITS.tailTokens} tokens of state`],
    ['Problems listed', DM_LIMITS.errors],
]));

process.stdout.write(out.join('\n\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
